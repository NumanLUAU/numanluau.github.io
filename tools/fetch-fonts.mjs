// downloads the self-hosted fonts into Site/vendor/fonts.
//   - Google Sans (variable, 400-700): latin + latin-ext
//   - Material Symbols Rounded: only the icons listed in tools/icons.txt
// run with: npm run fonts      (needs internet; the result is committed, so visitors never hit Google)
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'Site', 'vendor', 'fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

async function getText(url) {
	const response = await fetch(url, { headers: { 'User-Agent': UA } });
	if (!response.ok) throw new Error(`${response.status} ${url}\n${await response.text()}`);
	return response.text();
}

async function getFile(url, name) {
	const response = await fetch(url, { headers: { 'User-Agent': UA } });
	if (!response.ok) throw new Error(`${response.status} ${url}`);
	const data = Buffer.from(await response.arrayBuffer());
	await writeFile(join(out, name), data);
	console.log(`  ${name}  ${(data.length / 1024).toFixed(1)} KB`);
}

// css from google fonts is split into one @font-face per unicode range, with a comment naming the range.
function blocks(css) {
	return [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)].map(match => ({
		name: match[1],
		url: /url\(([^)]+)\)/.exec(match[2])[1],
		range: /unicode-range:\s*([^;]+);/.exec(match[2])?.[1],
	}));
}

await mkdir(out, { recursive: true });

console.log('Google Sans');
const sans = blocks(await getText('https://fonts.googleapis.com/css2?family=Google+Sans:wght@400..700&display=swap'));
const css = [];

for (const block of sans.filter(b => b.name === 'latin' || b.name === 'latin-ext')) {
	const file = `google-sans-${block.name}.woff2`;
	await getFile(block.url, file);
	css.push(`@font-face {\n\tfont-family: 'Google Sans';\n\tfont-style: normal;\n\tfont-weight: 400 700;\n\tfont-display: swap;\n\tsrc: url('./fonts/${file}') format('woff2');\n\tunicode-range: ${block.range};\n}`);
}

console.log('Material Symbols Rounded (subset)');
const icons = (await readFile(join(root, 'tools', 'icons.txt'), 'utf8')).split(/\s+/).filter(Boolean);
const symbolsUrlFull = `https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:FILL,wght@0..1,100..700&icon_names=${[...new Set(icons)].sort().join(',')}&display=block`;

// google falls back to the full font when the request url is longer than ~4000 characters.
if (symbolsUrlFull.length > 4000) {
	throw new Error(`tools/icons.txt has too many icons (request url is ${symbolsUrlFull.length} characters, the limit is about 4000). Remove some.`);
}

const symbolsCss = await getText(symbolsUrlFull);
const symbolsUrl = /url\(([^)]+)\)/.exec(symbolsCss)[1];
await getFile(symbolsUrl, 'material-symbols-rounded.woff2');

// google quietly returns the WHOLE font (1.4 MB) if even one icon name is invalid.
if ((await stat(join(out, 'material-symbols-rounded.woff2'))).size > 400 * 1024) {
	throw new Error('Material Symbols came back far too big: one of the names in tools/icons.txt is not a real icon. Remove it and run again.');
}

await writeFile(join(root, 'Site', 'vendor', 'fonts.css'), `/* generated by tools/fetch-fonts.mjs */\n${css.join('\n')}\n`);
console.log('wrote Site/vendor/fonts.css');
